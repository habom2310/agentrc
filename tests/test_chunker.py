import unittest
from pathlib import Path
import sys

src_path = Path(__file__).resolve().parent.parent / "src"
if str(src_path) not in sys.path:
    sys.path.insert(0, str(src_path))

from agentrc.chunker import (
    MarkdownChunk,
    parse_markdown_chunks,
    diff_chunks,
    compute_normalized_hash,
)


class TestChunker(unittest.TestCase):
    def test_parse_headers_and_hierarchy(self):
        sample = """# Main Section
Intro text here.

## Subsection A
Content for A.

### Sub-sub 1
Deep leaf.

## Subsection B
Content for B.
"""
        chunks = parse_markdown_chunks(sample)
        self.assertEqual(len(chunks), 4)

        c0 = chunks[0]
        self.assertEqual(c0.header, "Main Section")
        self.assertEqual(c0.level, 1)
        self.assertEqual(c0.path, ("Main Section",))
        self.assertIn("Intro text here.", c0.content)

        c1 = chunks[1]
        self.assertEqual(c1.header, "Subsection A")
        self.assertEqual(c1.level, 2)
        self.assertEqual(c1.path, ("Main Section", "Subsection A"))

        c2 = chunks[2]
        self.assertEqual(c2.header, "Sub-sub 1")
        self.assertEqual(c2.level, 3)
        self.assertEqual(c2.path, ("Main Section", "Subsection A", "Sub-sub 1"))

        c3 = chunks[3]
        self.assertEqual(c3.header, "Subsection B")
        self.assertEqual(c3.level, 2)
        self.assertEqual(c3.path, ("Main Section", "Subsection B"))

    def test_code_blocks_with_hash(self):
        sample = """# Code Examples
Here is Python code:

```python
# This is a python comment
def add(a, b):
    # Another comment
    return a + b
```

And some tilde block:

~~~bash
# Bash comment
echo "hello"
~~~

After code.
"""
        chunks = parse_markdown_chunks(sample)
        # Exactly one chunk because '#' inside fences must NOT be parsed as headers
        self.assertEqual(len(chunks), 1)
        self.assertEqual(chunks[0].header, "Code Examples")
        self.assertEqual(len(chunks[0].code_blocks), 2)
        self.assertIn("# This is a python comment", chunks[0].code_blocks[0])
        self.assertIn("# Bash comment", chunks[0].code_blocks[1])

    def test_hash_normalization(self):
        text_crlf = "Rule text line 1\r\nRule text line 2   \r\n"
        text_lf = "Rule text line 1\nRule text line 2\n\n"
        different_text = "Rule text line 1\nRule text line 3\n"

        hash1 = compute_normalized_hash(text_crlf)
        hash2 = compute_normalized_hash(text_lf)
        hash3 = compute_normalized_hash(different_text)

        self.assertEqual(hash1, hash2)
        self.assertNotEqual(hash1, hash3)

    def test_diff_chunks(self):
        source_text = """# Rule A
Content A.

# Rule B
Content B modified.

# Rule C
Content C (new).
"""
        target_text = """# Rule A
Content A.

# Rule B
Content B original.

# Rule D
Content D (old).
"""
        source_chunks = parse_markdown_chunks(source_text)
        target_chunks = parse_markdown_chunks(target_text)

        diff = diff_chunks(source_chunks, target_chunks)

        # Identical: Rule A
        self.assertEqual(len(diff["identical"]), 1)
        self.assertEqual(diff["identical"][0].header, "Rule A")

        # Modified: Rule B
        self.assertEqual(len(diff["modified"]), 1)
        self.assertEqual(diff["modified"][0]["source"].header, "Rule B")
        self.assertEqual(diff["modified"][0]["target"].header, "Rule B")

        # Added in source: Rule C
        self.assertEqual(len(diff["added"]), 1)
        self.assertEqual(diff["added"][0].header, "Rule C")

        # Removed from target: Rule D
        self.assertEqual(len(diff["removed"]), 1)
        self.assertEqual(diff["removed"][0].header, "Rule D")

    def test_prelude_handling(self):
        # Prelude with autogenerated HTML guard should be ignored
        with_guard = """<!-- AUTOGENERATED BY AGENTRC - DO NOT EDIT DIRECTLY. EDIT IN ~/.agentrc/ -->

# Heading
Content
"""
        chunks = parse_markdown_chunks(with_guard)
        self.assertEqual(len(chunks), 1)
        self.assertEqual(chunks[0].header, "Heading")

        # Non-comment prelude text should be preserved as level 0 chunk
        with_prelude = """Preamble note before rules.

# Heading
Content
"""
        chunks2 = parse_markdown_chunks(with_prelude)
        self.assertEqual(len(chunks2), 2)
        self.assertEqual(chunks2[0].level, 0)
        self.assertEqual(chunks2[0].header, "")
        self.assertEqual(chunks2[0].path, ())
        self.assertIn("Preamble note", chunks2[0].content)

    def test_c_sharp_and_closing_hashes(self):
        sample = """## C#
Guidelines for C# development.

## Header With Closing Hashes ###
Content here.
"""
        chunks = parse_markdown_chunks(sample)
        self.assertEqual(len(chunks), 2)
        self.assertEqual(chunks[0].header, "C#")
        self.assertEqual(chunks[1].header, "Header With Closing Hashes")


if __name__ == "__main__":
    unittest.main()
