"""
End-to-end sandbox test for agentrc.
Validates the entire lifecycle (detect -> init -> link -> project -> doctor)
in a 100% isolated temporary directory without touching the user's real AI configurations.
"""

import unittest
import tempfile
import json
from pathlib import Path
import sys
import shutil

src_path = Path(__file__).resolve().parent.parent / "src"
if str(src_path) not in sys.path:
    sys.path.insert(0, str(src_path))

from agentrc.detector import set_custom_home, detect_platforms, get_home_dir, get_hub_dir
from agentrc.scaffold import init_hub
from agentrc.linker import link_skills_for_claude, link_skills_for_gemini, link_skills_for_codex
from agentrc.projector import (
    project_gemini_rules,
    project_claude_rules,
    project_codex_rules,
    project_subagents
)
from agentrc.doctor import run_doctor
from agentrc.token_budget import audit_budget


class TestSandboxE2E(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.sandbox = Path(self.temp_dir.name).resolve()
        set_custom_home(self.sandbox)
        self.templates_dir = Path(__file__).resolve().parent.parent / "templates"

        # Pre-seed mock user directories and existing configurations
        self.mock_claude = self.sandbox / ".claude"
        self.mock_gemini = self.sandbox / ".gemini" / "config"
        self.mock_codex = self.sandbox / ".codex"

        self.mock_claude.mkdir(parents=True, exist_ok=True)
        self.mock_gemini.mkdir(parents=True, exist_ok=True)
        self.mock_codex.mkdir(parents=True, exist_ok=True)

        # Existing rules and mock skills
        (self.mock_claude / "CLAUDE.md").write_text("# Old Claude Rules\nCustom line\n", encoding="utf-8")
        (self.sandbox / ".gemini" / "GEMINI.md").write_text("# Old Gemini Rules\nCustom line\n", encoding="utf-8")
        (self.mock_gemini / "skills.json").write_text(json.dumps({"entries": []}), encoding="utf-8")
        (self.mock_codex / "AGENTS.md").write_text("# Old Codex Rules\nCustom line\n", encoding="utf-8")

        mock_claude_skill = self.mock_claude / "skills" / "mock-claude-tool"
        mock_claude_skill.mkdir(parents=True, exist_ok=True)
        (mock_claude_skill / "SKILL.md").write_text("---\nname: mock-claude\ndescription: Mock\n---\nBody", encoding="utf-8")

    def tearDown(self):
        set_custom_home(None)
        try:
            self.temp_dir.cleanup()
        except Exception:
            pass

    def test_full_sandboxed_workflow(self):
        # 1. Detection in Sandbox
        rep = detect_platforms()
        self.assertEqual(rep["hub"]["exists"], False)
        self.assertEqual(rep["platforms"]["claude"]["detected"], True)
        self.assertEqual(rep["platforms"]["antigravity"]["detected"], True)
        self.assertEqual(rep["platforms"]["codex"]["detected"], True)

        # 2. Initialization & Whitelist Backup
        init_res = init_hub(template_dir=self.templates_dir, force=True)
        hub = self.sandbox / ".agentrc"
        self.assertTrue((hub / "agentrc.json").is_file())
        self.assertTrue(len(init_res["backed_up_files"]) >= 3)
        # Verify old files backed up safely
        backup_root = hub / "backups"
        self.assertTrue(any(backup_root.iterdir()))

        # 3. Linking Skills
        ok_c, _ = link_skills_for_claude()
        ok_g, _ = link_skills_for_gemini()
        ok_x, _ = link_skills_for_codex()

        self.assertTrue(ok_c)
        self.assertTrue(ok_g)
        self.assertTrue(ok_x)

        # Verify Codex skill manifests projected
        mock_openai_yaml = hub / "skills" / "mock-claude-tool" / "agents" / "openai.yaml"
        self.assertTrue(mock_openai_yaml.is_file())
        self.assertIn("Mock Claude", mock_openai_yaml.read_text(encoding="utf-8"))

        # 4. Compiled Projections
        ok_pg, _ = project_gemini_rules()
        ok_pc, _ = project_claude_rules()
        ok_px, _ = project_codex_rules()
        ok_pa, _ = project_subagents()

        self.assertTrue(ok_pg)
        self.assertTrue(ok_pc)
        self.assertTrue(ok_px)
        self.assertTrue(ok_pa)

        # Verify projections have header guard
        gemini_txt = (self.sandbox / ".gemini" / "GEMINI.md").read_text(encoding="utf-8")
        self.assertIn("AUTOGENERATED BY AGENTRC", gemini_txt)

        codex_txt = (self.sandbox / ".codex" / "AGENTS.md").read_text(encoding="utf-8")
        self.assertIn("AUTOGENERATED BY AGENTRC", codex_txt)

        # Verify Antigravity subagent tool schemas
        gemini_imp = (self.sandbox / ".gemini" / "config" / "agents" / "implementer.md").read_text(encoding="utf-8")
        self.assertIn("tools:\n  - read\n  - edit\n  - terminal", gemini_imp)
        self.assertIn("subagent: true", gemini_imp)

        gemini_rev = (self.sandbox / ".gemini" / "config" / "agents" / "reviewer.md").read_text(encoding="utf-8")
        self.assertIn("tools:\n  - read\n  - terminal", gemini_rev)
        self.assertIn("subagent: true", gemini_rev)

        # 5. Doctor Health Check
        doc_res = run_doctor(fix=False)
        self.assertEqual(doc_res["status"], "PASS")
        self.assertEqual(len(doc_res["issues"]), 0)

        # 6. Budget Audit
        budget = audit_budget()
        self.assertEqual(budget["status"], "PASS (LEAN)")
        self.assertLess(budget["total_boot_tokens"], 2000)


if __name__ == "__main__":
    unittest.main()
