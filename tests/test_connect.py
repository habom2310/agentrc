import unittest
import tempfile
import json
from pathlib import Path
import sys

src_path = Path(__file__).resolve().parent.parent / "src"
if str(src_path) not in sys.path:
    sys.path.insert(0, str(src_path))

from agentrc.detector import set_custom_home, detect_platforms
from agentrc.scaffold import init_hub
from agentrc.connect import connect_cursor, connect_windsurf, connect_platform
from agentrc.doctor import run_doctor


class TestConnect(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.home_dir = Path(self.temp_dir.name) / "home"
        self.hub_dir = self.home_dir / ".agentrc"

        self.home_dir.mkdir(parents=True, exist_ok=True)
        self.hub_dir.mkdir(parents=True, exist_ok=True)

        set_custom_home(self.home_dir, self.hub_dir)

        # Initialize hub with starter files
        template_dir = Path(__file__).resolve().parent.parent / "templates"
        init_hub(template_dir=template_dir)

    def tearDown(self):
        set_custom_home(None, None)
        self.temp_dir.cleanup()

    def test_connect_cursor(self):
        ok, msg = connect_cursor()
        self.assertTrue(ok)

        cursor_dir = self.home_dir / ".cursor"
        self.assertTrue(cursor_dir.is_dir())

        # Check skills junction
        cursor_skills = cursor_dir / "skills"
        self.assertTrue(cursor_skills.exists())
        self.assertEqual(cursor_skills.resolve(), (self.hub_dir / "skills").resolve())

        # Check rules
        mdc_file = cursor_dir / "rules" / "agentrc.mdc"
        self.assertTrue(mdc_file.is_file())
        mdc_text = mdc_file.read_text(encoding="utf-8")
        self.assertIn("globs: *", mdc_text)
        self.assertIn("AUTOGENERATED BY AGENTRC", mdc_text)
        self.assertIn("1. Think Before Coding", mdc_text)

        cursorrules = self.home_dir / ".cursorrules"
        self.assertTrue(cursorrules.is_file())

        # Check manifest update
        manifest = json.loads((self.hub_dir / "agentrc.json").read_text(encoding="utf-8"))
        self.assertTrue(manifest["platforms"]["cursor"]["enabled"])

        # Check detector
        report = detect_platforms()
        self.assertTrue(report["platforms"]["cursor"]["detected"])
        self.assertTrue(report["platforms"]["cursor"]["rules_exists"])
        self.assertTrue(report["platforms"]["cursor"]["skills_linked"])

        # Check doctor passes cursor checks
        doc = run_doctor()
        self.assertIn("Cursor skills junction intact", doc["passed_checks"])
        self.assertIn("Cursor rules projected from hub", doc["passed_checks"])

    def test_connect_windsurf(self):
        ok, msg = connect_windsurf()
        self.assertTrue(ok)

        windsurf_dir = self.home_dir / ".codeium" / "windsurf"
        self.assertTrue(windsurf_dir.is_dir())

        # Check skills junction
        ws_skills = windsurf_dir / "skills"
        self.assertTrue(ws_skills.exists())
        self.assertEqual(ws_skills.resolve(), (self.hub_dir / "skills").resolve())

        # Check rules
        global_rules = windsurf_dir / "memories" / "global_rules.md"
        self.assertTrue(global_rules.is_file())
        self.assertIn("1. Think Before Coding", global_rules.read_text(encoding="utf-8"))

        windsurfrules = self.home_dir / ".windsurfrules"
        self.assertTrue(windsurfrules.is_file())

        # Check manifest update
        manifest = json.loads((self.hub_dir / "agentrc.json").read_text(encoding="utf-8"))
        self.assertTrue(manifest["platforms"]["windsurf"]["enabled"])

        # Check detector
        report = detect_platforms()
        self.assertTrue(report["platforms"]["windsurf"]["detected"])
        self.assertTrue(report["platforms"]["windsurf"]["rules_exists"])
        self.assertTrue(report["platforms"]["windsurf"]["skills_linked"])

        # Check doctor
        doc = run_doctor()
        self.assertIn("Windsurf skills junction intact", doc["passed_checks"])
        self.assertIn("Windsurf rules projected from hub", doc["passed_checks"])

    def test_connect_platform_dispatcher(self):
        ok, msg = connect_platform("cursor")
        self.assertTrue(ok)

        ok_bad, msg_bad = connect_platform("unknown_assistant")
        self.assertFalse(ok_bad)
        self.assertIn("Unsupported platform", msg_bad)

        ok_reject, msg_reject = connect_platform("gemini", target_dir=Path("/tmp/custom"))
        self.assertFalse(ok_reject)
        self.assertIn("Custom --target-dir is not supported", msg_reject)


if __name__ == "__main__":
    unittest.main()
