"""
Markdown AST chunker for agentrc.
Parses markdown files into hierarchical section chunks with normalized hashing,
fenced code block awareness, and drift diffing.
"""

from dataclasses import dataclass, field
import hashlib
from pathlib import Path
import re


@dataclass
class MarkdownChunk:
    header: str
    level: int
    path: tuple[str, ...]
    content: str
    raw: str
    normalized_hash: str
    code_blocks: list[str] = field(default_factory=list)


def normalize_content(text: str) -> str:
    """
    Normalizes content for deterministic hashing:
    - Normalizes \r\n and \r to \n
    - Strips trailing whitespace on each line
    - Strips leading and trailing blank lines / whitespace
    """
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = [line.rstrip() for line in text.splitlines()]
    return "\n".join(lines).strip()


def compute_normalized_hash(text: str) -> str:
    """Computes SHA-256 hex digest of normalized content."""
    normalized = normalize_content(text)
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


def parse_markdown_chunks(text: str) -> list[MarkdownChunk]:
    """
    Parses markdown text into hierarchical MarkdownChunk objects.
    - Honors fenced code blocks (``` and ~~~) so '#' inside code blocks are not headers.
    - Strips or ignores HTML comments (like agentrc autogenerated guards).
    - Preserves prelude text as a level 0 chunk if non-empty.
    """
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")

    chunks: list[MarkdownChunk] = []

    in_code_block = False
    fence_char = ""
    fence_len = 0
    current_code_block_lines: list[str] = []

    header_stack: list[tuple[int, str]] = []

    current_header: str | None = None
    current_level: int = 0
    current_content_lines: list[str] = []
    current_raw_lines: list[str] = []
    current_code_blocks: list[str] = []

    def finalize_current_chunk():
        nonlocal current_header, current_level, current_content_lines, current_raw_lines, current_code_blocks
        if current_header is None:
            # Level 0 prelude
            raw_text = "\n".join(current_raw_lines)
            stripped_prelude = re.sub(r"<!--.*?-->", "", raw_text, flags=re.DOTALL).strip()
            if stripped_prelude:
                content_text = stripped_prelude
                nhash = compute_normalized_hash(content_text)
                clean_raw = re.sub(r"<!--.*?-->\n*", "", raw_text, flags=re.DOTALL).strip()
                chunks.append(
                    MarkdownChunk(
                        header="",
                        level=0,
                        path=(),
                        content=content_text,
                        raw=clean_raw + "\n" if clean_raw else "",
                        normalized_hash=nhash,
                        code_blocks=list(current_code_blocks),
                    )
                )
        else:
            content_text = "\n".join(current_content_lines).rstrip()
            raw_text = "\n".join(current_raw_lines)
            path_tuple = tuple(h for _, h in header_stack)
            nhash = compute_normalized_hash(content_text)
            chunks.append(
                MarkdownChunk(
                    header=current_header,
                    level=current_level,
                    path=path_tuple,
                    content=content_text,
                    raw=raw_text,
                    normalized_hash=nhash,
                    code_blocks=list(current_code_blocks),
                )
            )

        current_content_lines = []
        current_raw_lines = []
        current_code_blocks = []

    fence_pattern = re.compile(r"^(\s*)(`{3,}|~{3,})(.*)$")
    header_pattern = re.compile(r"^(#{1,6})\s+(.*)$")

    for line in lines:
        if in_code_block:
            current_raw_lines.append(line)
            current_content_lines.append(line)
            current_code_block_lines.append(line)
            close_match = re.match(r"^\s*(`{3,}|~{3,})\s*$", line)
            if close_match:
                c_del = close_match.group(1)
                if c_del[0] == fence_char and len(c_del) >= fence_len:
                    in_code_block = False
                    current_code_blocks.append("\n".join(current_code_block_lines))
                    current_code_block_lines = []
            continue

        fence_match = fence_pattern.match(line)
        if fence_match:
            in_code_block = True
            fence_char = fence_match.group(2)[0]
            fence_len = len(fence_match.group(2))
            current_raw_lines.append(line)
            current_content_lines.append(line)
            current_code_block_lines = [line]
            continue

        header_match = header_pattern.match(line)
        if header_match:
            finalize_current_chunk()

            level = len(header_match.group(1))
            raw_header = header_match.group(2).strip()
            header_text = re.sub(r"\s+#+\s*$", "", raw_header).strip()

            while header_stack and header_stack[-1][0] >= level:
                header_stack.pop()
            header_stack.append((level, header_text))

            current_header = header_text
            current_level = level
            current_raw_lines = [line]
            current_content_lines = []
            current_code_blocks = []
        else:
            current_raw_lines.append(line)
            current_content_lines.append(line)

    finalize_current_chunk()
    return chunks


def diff_chunks(
    source_chunks: list[MarkdownChunk],
    target_chunks: list[MarkdownChunk],
) -> dict:
    """
    Compares two lists of chunks by header path and normalized_hash.
    Returns:
      'identical': list of chunks present in both with identical normalized_hash
      'modified': list of dicts {'source': s, 'target': t} for chunks having same path but differing hashes
      'added': list of chunks present in source but missing from target
      'removed': list of chunks present in target but missing from source
    """
    target_by_path: dict[tuple[str, ...], MarkdownChunk] = {}
    for c in target_chunks:
        target_by_path[c.path] = c

    source_by_path: dict[tuple[str, ...], MarkdownChunk] = {}
    for c in source_chunks:
        source_by_path[c.path] = c

    identical: list[MarkdownChunk] = []
    modified: list[dict[str, MarkdownChunk]] = []
    added: list[MarkdownChunk] = []
    removed: list[MarkdownChunk] = []

    for s in source_chunks:
        if s.path in target_by_path:
            t = target_by_path[s.path]
            if s.normalized_hash == t.normalized_hash:
                identical.append(s)
            else:
                modified.append({"source": s, "target": t})
        else:
            added.append(s)

    for t in target_chunks:
        if t.path not in source_by_path:
            removed.append(t)

    return {
        "identical": identical,
        "modified": modified,
        "added": added,
        "removed": removed,
    }
