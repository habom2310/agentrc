"""
Deterministic projector for rules and subagents.
Compiles universal rules and agent templates into host-specific manifests.
"""

from pathlib import Path
import re
from agentrc.detector import get_home_dir, get_hub_dir

HEADER_GUARD = "<!-- AUTOGENERATED BY AGENTRC - DO NOT EDIT DIRECTLY. EDIT IN ~/.agentrc/ -->\n\n"


def project_gemini_rules() -> tuple[bool, str]:
    home = get_home_dir()
    hub = get_hub_dir()
    rules_dir = hub / "rules"

    if not rules_dir.is_dir():
        return False, f"Rules directory not found: {rules_dir}"

    parts = [HEADER_GUARD]

    # 1. common.md
    common = rules_dir / "common.md"
    if common.is_file():
        parts.append(common.read_text(encoding="utf-8").strip())

    # 2. code-tools.md
    code_tools = rules_dir / "code-tools.md"
    if code_tools.is_file():
        parts.append(code_tools.read_text(encoding="utf-8").strip())

    # 3. handoffs.md
    handoffs = rules_dir / "handoffs.md"
    if handoffs.is_file():
        parts.append(handoffs.read_text(encoding="utf-8").strip())

    # 4. overrides/agy.md
    agy_override = rules_dir / "overrides" / "agy.md"
    if agy_override.is_file():
        parts.append(agy_override.read_text(encoding="utf-8").strip())

    content = "\n\n".join(parts) + "\n"

    target1 = home / ".gemini" / "GEMINI.md"
    target2 = home / ".gemini" / "config" / "GEMINI.md"

    target1.parent.mkdir(parents=True, exist_ok=True)
    target1.write_text(content, encoding="utf-8")

    if target2.parent.is_dir():
        target2.write_text(content, encoding="utf-8")

    return True, f"Projected GEMINI.md ({len(content)} chars)"


def project_claude_rules(use_imports: bool = True) -> tuple[bool, str]:
    home = get_home_dir()
    hub = get_hub_dir()
    rules_dir = hub / "rules"
    target = home / ".claude" / "CLAUDE.md"

    if use_imports:
        content = (
            f"{HEADER_GUARD}"
            f"@{(rules_dir / 'common.md').as_posix()}\n"
            f"@{(rules_dir / 'code-tools.md').as_posix()}\n"
            f"@{(rules_dir / 'handoffs.md').as_posix()}\n"
            f"@{(rules_dir / 'overrides' / 'claude.md').as_posix()}\n"
        )
    else:
        parts = [HEADER_GUARD]
        for f in ["common.md", "code-tools.md", "handoffs.md", "overrides/claude.md"]:
            p = rules_dir / f
            if p.is_file():
                parts.append(p.read_text(encoding="utf-8").strip())
        content = "\n\n".join(parts) + "\n"

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    return True, f"Projected CLAUDE.md ({len(content)} chars)"


