def parse_frontmatter(content: str) -> tuple[dict, str]:
    if not content.startswith("---"):
        return {}, content
    parts = content.split("---", 2)
    if len(parts) < 3:
        return {}, content
    yaml_text = parts[1]
    body = parts[2]
    meta = {}
    for line in yaml_text.strip().splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, body


def project_subagents() -> tuple[bool, list[str]]:
    home = get_home_dir()
    hub = get_hub_dir()
    agents_dir = hub / "agents"
    if not agents_dir.is_dir():
        return False, ["No agents directory in hub"]

    gemini_agents = home / ".gemini" / "config" / "agents"
    claude_agents = home / ".claude" / "agents"

    gemini_agents.mkdir(parents=True, exist_ok=True)
    claude_agents.mkdir(parents=True, exist_ok=True)

    results = []

    for f in agents_dir.glob("*.md"):
        content = f.read_text(encoding="utf-8")
        meta, body = parse_frontmatter(content)
        name = meta.get("name", f.stem)
        desc = meta.get("description", "")
        tier = meta.get("tier", "inherit")
        effort = meta.get("effort", "medium")
        mode = meta.get("mode", "read-write")

        # Project for AGY (omit tools, map models to inherit / pro / flash)
        agy_model = "inherit"
        if tier == "pro" or tier == "smart":
            agy_model = "pro"
        elif tier == "fast" or tier == "flash":
            agy_model = "flash"

        agy_fm = [
            "---",
            f"name: {name}",
            f"description: {desc}",
            f"model: {agy_model}",
            f"effort: {effort}",
            "subagent: true",
        ]
        if mode == "read-write" or meta.get("enable_write_tools") == "true":
            agy_fm.extend([
                "tools:",
                "  - run_command",
                "  - write_file",
                "  - edit_file",
                "  - read_file",
            ])
        else:
            agy_fm.extend([
                "tools:",
                "  - run_command",
                "  - read_file",
            ])
        agy_fm.append("---")
        agy_content = "\n".join(agy_fm) + body
        (gemini_agents / f"{name}.md").write_text(agy_content, encoding="utf-8")

        # Project for Claude Code (inject tools & claude models)
        claude_model = "haiku" if (tier == "fast" or tier == "inherit") else "sonnet"
        claude_tools = "Bash, Read, Edit, Write, Glob, Grep" if mode == "read-write" else "Bash, Read, Glob, Grep"
        claude_fm = [
            "---",
            f"name: {name}",
            f"description: {desc}",
            f"model: {claude_model}",
            f"effort: {effort}",
            f"tools: {claude_tools}",
            "---",
        ]
        claude_content = "\n".join(claude_fm) + body
        (claude_agents / f"{name}.md").write_text(claude_content, encoding="utf-8")

        results.append(f"Projected subagent: {name}")

    return True, results
