"""
Rule promoter and drift detection engine for agentrc.
Detects rule drift across downstream AI platforms and cleanly promotes rules back into the hub.
"""

from pathlib import Path
from agentrc.detector import get_home_dir, get_hub_dir
from agentrc.chunker import MarkdownChunk, parse_markdown_chunks, diff_chunks
from agentrc.projector import (
    HEADER_GUARD,
    PLATFORM_RULE_FILES,
    project_gemini_rules,
    project_claude_rules,
    project_codex_rules,
    project_cursor_rules,
    project_windsurf_rules,
)


def _get_expected_rules_text(platform: str, rules_dir: Path) -> str:
    """Builds the expected projected markdown text for a platform from hub rules."""
    files = PLATFORM_RULE_FILES.get(platform, ["common.md", "code-tools.md", "handoffs.md"])
    parts = [HEADER_GUARD.strip()]
    for f in files:
        p = rules_dir / f
        if p.is_file():
            parts.append(p.read_text(encoding="utf-8").strip())
    return "\n\n".join(parts) + "\n"


def detect_rule_drift(home_dir: Path | None = None, hub_dir: Path | None = None) -> dict:
    """
    Checks downstream target files against expected projections from hub/rules/.
    Returns dictionary of drifted/added/modified/removed chunks per platform.
    """
    if home_dir is None:
        home_dir = get_home_dir()
    if hub_dir is None:
        hub_dir = get_hub_dir()

    rules_dir = hub_dir / "rules"

    platform_files = {
        "gemini": home_dir / ".gemini" / "GEMINI.md",
        "claude": home_dir / ".claude" / "CLAUDE.md",
        "codex": home_dir / ".codex" / "AGENTS.md",
    }

    report = {}

    for platform, target_file in platform_files.items():
        if not target_file.is_file():
            report[platform] = {
                "file": str(target_file),
                "exists": False,
                "has_drift": False,
                "added": [],
                "modified": [],
                "removed": [],
                "identical": [],
            }
            continue

        raw_downstream = target_file.read_text(encoding="utf-8")

        is_import_manifest = platform == "claude" and any(
            line.strip().startswith("@") and ("rules/" in line or "common.md" in line)
            for line in raw_downstream.splitlines()
        )
        if is_import_manifest:
            # Claude uses @import lines. Any unimported markdown lines appended downstream are drift.
            non_import_lines = [
                line for line in raw_downstream.splitlines()
                if not line.strip().startswith("@") and "AUTOGENERATED BY AGENTRC" not in line
            ]
            unimported_text = "\n".join(non_import_lines).strip()
            downstream_chunks = parse_markdown_chunks(unimported_text) if unimported_text else []
            expected_chunks = []
            diff = diff_chunks(downstream_chunks, expected_chunks)
        else:
            expected_text = _get_expected_rules_text(platform, rules_dir)
            expected_chunks = parse_markdown_chunks(expected_text)
            downstream_chunks = parse_markdown_chunks(raw_downstream)
            diff = diff_chunks(downstream_chunks, expected_chunks)

        has_drift = bool(diff["added"] or diff["modified"] or diff["removed"])

        report[platform] = {
            "file": str(target_file),
            "exists": True,
            "has_drift": has_drift,
            "added": diff["added"],
            "modified": diff["modified"],
            "removed": diff["removed"],
            "identical": diff["identical"],
        }

    return report


def promote_chunk(
    chunk: MarkdownChunk,
    target_rule_file: str = "common.md",
    hub_dir: Path | None = None,
    reproject: bool = True,
) -> tuple[bool, str]:
    """
    Appends or merges the chunk's raw markdown cleanly into hub/rules/{target_rule_file}.
    Optionally re-runs projectors to ensure the promoted rule is synchronized across platforms.
    Returns (success, message).
    """
    if hub_dir is None:
        hub_dir = get_hub_dir()

    rules_dir = (hub_dir / "rules").resolve()
    rules_dir.mkdir(parents=True, exist_ok=True)

    if not target_rule_file.endswith(".md"):
        target_rule_file += ".md"

    target_path = (rules_dir / target_rule_file).resolve()
    if not target_path.is_relative_to(rules_dir):
        return False, f"Target file must reside inside hub rules directory: {target_rule_file}"

    if target_path.is_file():
        # Normalize CRLF/CR to LF for reliable in-place matching
        existing_text = target_path.read_text(encoding="utf-8").replace("\r\n", "\n").replace("\r", "\n")
        existing_chunks = parse_markdown_chunks(existing_text)

        target_chunk = None
        for ec in existing_chunks:
            if ec.path == chunk.path:
                target_chunk = ec
                break

        if target_chunk and target_chunk.raw in existing_text:
            # Preserve spacing between sections so next header isn't concatenated
            new_text = existing_text.replace(target_chunk.raw, chunk.raw.rstrip() + "\n", 1)
        else:
            # Check if this is a sub-section whose parent exists
            inserted = False
            if len(chunk.path) > 1:
                parent_path = chunk.path[:-1]
                parent_idx = None
                for idx, ec in enumerate(existing_chunks):
                    if ec.path == parent_path:
                        parent_idx = idx
                        break

                if parent_idx is not None:
                    # Find insertion point: after parent and all its existing descendants
                    parent_level = existing_chunks[parent_idx].level
                    insert_after_chunk = existing_chunks[parent_idx]
                    for next_idx in range(parent_idx + 1, len(existing_chunks)):
                        next_chunk = existing_chunks[next_idx]
                        if next_chunk.level > parent_level:
                            insert_after_chunk = next_chunk
                        else:
                            break

                    target_raw = insert_after_chunk.raw
                    if target_raw in existing_text:
                        replacement = target_raw.rstrip() + "\n\n" + chunk.raw.strip() + "\n\n"
                        new_text = existing_text.replace(target_raw, replacement, 1)
                        inserted = True

            if not inserted:
                new_text = existing_text.rstrip() + "\n\n" + chunk.raw.strip() + "\n"
    else:
        new_text = chunk.raw.strip() + "\n"

    target_path.parent.mkdir(parents=True, exist_ok=True)
    target_path.write_text(new_text, encoding="utf-8")

    if reproject:
        project_gemini_rules()
        project_claude_rules()
        project_codex_rules()
        project_cursor_rules()
        project_windsurf_rules()

    return True, f"Promoted rule '{chunk.header}' into {target_rule_file}"
