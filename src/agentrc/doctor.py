"""
Diagnostic and self-healing engine for agentrc.
Detects configuration drift, severed junctions, and missing projections.
"""

from pathlib import Path
import json
from agentrc.detector import get_home_dir, get_hub_dir
from agentrc.linker import link_skills_for_claude, link_skills_for_gemini, link_skills_for_codex
from agentrc.projector import project_gemini_rules, project_claude_rules, project_codex_rules, project_subagents


def run_doctor(fix: bool = False) -> dict:
    home = get_home_dir()
    hub = get_hub_dir()

    issues = []
    checks = []

    # 1. Hub Manifest Check
    manifest = hub / "agentrc.json"
    if not manifest.is_file():
        issues.append("agentrc hub is not initialized (~/.agentrc/agentrc.json missing)")
    else:
        checks.append("agentrc hub manifest present")

    # 2. Claude Skills Junction Check
    claude_skills = home / ".claude" / "skills"
    hub_skills = hub / "skills"
    if not claude_skills.exists():
        issues.append("~/.claude/skills does not exist")
    elif claude_skills.resolve() != hub_skills.resolve():
        issues.append(f"~/.claude/skills points to {claude_skills.resolve()} instead of {hub_skills.resolve()}")
    else:
        checks.append("Claude Code skills junction intact")

    # 3. Antigravity Skills JSON Check
    gemini_skills_json = home / ".gemini" / "config" / "skills.json"
    if not gemini_skills_json.is_file():
        issues.append("~/.gemini/config/skills.json missing")
    else:
        try:
            data = json.loads(gemini_skills_json.read_text(encoding="utf-8"))
            paths = [e.get("path", "") for e in data.get("entries", [])]
            hub_path_str = str(hub_skills.resolve()).replace("\\", "/")
            if any(hub_path_str.lower() in p.lower() for p in paths):
                checks.append("Antigravity skills.json correctly references hub skills")
            else:
                issues.append("Antigravity skills.json does not reference ~/.agentrc/skills")
        except Exception as e:
            issues.append(f"Could not read skills.json: {e}")

    # 4. Rules Projection Check
    gemini_rules = home / ".gemini" / "GEMINI.md"
    if not gemini_rules.is_file():
        issues.append("~/.gemini/GEMINI.md missing")
    else:
        txt = gemini_rules.read_text(encoding="utf-8")
        if "AUTOGENERATED BY AGENTRC" in txt:
            checks.append("GEMINI.md projected cleanly from hub")
        else:
            issues.append("GEMINI.md does not have agentrc header guard (manual override or drift)")

    claude_rules = home / ".claude" / "CLAUDE.md"
    if not claude_rules.is_file():
        issues.append("~/.claude/CLAUDE.md missing")
    else:
        txt = claude_rules.read_text(encoding="utf-8")
        if "@" in txt or "AUTOGENERATED BY AGENTRC" in txt:
            checks.append("CLAUDE.md links or projects cleanly from hub")
        else:
            issues.append("CLAUDE.md does not reference agentrc rules")

    # 5. Codex Rules & Skills Check
    codex_dir = home / ".codex"
    if codex_dir.is_dir():
        codex_rules = codex_dir / "AGENTS.md"
        if not codex_rules.is_file():
            issues.append("~/.codex/AGENTS.md missing")
        else:
            txt = codex_rules.read_text(encoding="utf-8")
            if "AUTOGENERATED BY AGENTRC" in txt:
                checks.append("Codex AGENTS.md projected cleanly from hub")
            else:
                issues.append("Codex AGENTS.md does not have agentrc header guard")

        codex_skills = codex_dir / "skills"
        if codex_skills.exists() and codex_skills.resolve() == hub_skills.resolve():
            checks.append("Codex skills junction intact")
        elif codex_skills.exists():
            issues.append("~/.codex/skills is not linked to ~/.agentrc/skills")
        else:
            issues.append("~/.codex/skills does not exist")

        # Check Codex skill manifests
        missing_manifests = []
        if hub_skills.is_dir():
            for s_dir in hub_skills.iterdir():
                if s_dir.is_dir() and (s_dir / "SKILL.md").is_file() and not (s_dir / "agents" / "openai.yaml").is_file():
                    missing_manifests.append(s_dir.name)
        if missing_manifests:
            issues.append(f"Codex skill manifests missing in {len(missing_manifests)} skill(s)")
        else:
            checks.append("Codex skill manifests (openai.yaml) present")

    # 6. Cursor Check (if connected or actively configured)
    cursor_dir = home / ".cursor"
    cursor_skills = cursor_dir / "skills"
    cursor_rules = cursor_dir / "rules" / "agentrc.mdc"
    cursor_legacy = home / ".cursorrules"

    cursor_enabled = False
    manifest_file = hub / "agentrc.json"
    if manifest_file.is_file():
        try:
            m_data = json.loads(manifest_file.read_text(encoding="utf-8"))
            cursor_enabled = m_data.get("platforms", {}).get("cursor", {}).get("enabled", False)
        except Exception:
            pass

    if cursor_enabled or cursor_skills.exists() or cursor_rules.is_file() or cursor_legacy.is_file():
        if cursor_skills.exists() and cursor_skills.resolve() == hub_skills.resolve():
            checks.append("Cursor skills junction intact")
        elif cursor_skills.exists():
            issues.append("~/.cursor/skills is not linked to ~/.agentrc/skills")
        else:
            issues.append("~/.cursor/skills does not exist")

        if cursor_rules.is_file() or cursor_legacy.is_file():
            checks.append("Cursor rules projected from hub")
        else:
            issues.append("Cursor rules missing (~/.cursor/rules/agentrc.mdc or ~/.cursorrules)")

    # 7. Windsurf Check (if connected or actively configured)
    windsurf_dir = home / ".codeium" / "windsurf"
    if not windsurf_dir.is_dir():
        windsurf_dir = home / ".windsurf"
    windsurf_skills = windsurf_dir / "skills"
    ws_rules = windsurf_dir / "memories" / "global_rules.md"
    ws_legacy = home / ".windsurfrules"

    windsurf_enabled = False
    if manifest_file.is_file():
        try:
            m_data = json.loads(manifest_file.read_text(encoding="utf-8"))
            windsurf_enabled = m_data.get("platforms", {}).get("windsurf", {}).get("enabled", False)
        except Exception:
            pass

    if windsurf_enabled or windsurf_skills.exists() or ws_rules.is_file() or ws_legacy.is_file():
        if windsurf_skills.exists() and windsurf_skills.resolve() == hub_skills.resolve():
            checks.append("Windsurf skills junction intact")
        elif windsurf_skills.exists():
            issues.append("Windsurf skills directory is not linked to ~/.agentrc/skills")
        else:
            issues.append("Windsurf skills directory does not exist")

        if ws_rules.is_file() or ws_legacy.is_file():
            checks.append("Windsurf rules projected from hub")
        else:
            issues.append("Windsurf rules missing")

    # 8. MCP Registry Check
    from agentrc.mcp_sync import get_mcp_status, sync_mcp_servers
    mcp_st = get_mcp_status(home, hub)
    if not mcp_st["hub"]["exists"]:
        issues.append("~/.agentrc/mcp/servers.json missing")
    elif not mcp_st["in_sync"]:
        drift_details = []
        if mcp_st["missing_in_claude"]:
            drift_details.append(f"missing in Claude: {', '.join(mcp_st['missing_in_claude'])}")
        if mcp_st["missing_in_gemini"]:
            drift_details.append(f"missing in Antigravity: {', '.join(mcp_st['missing_in_gemini'])}")
        if mcp_st["untracked_in_claude"]:
            drift_details.append(f"untracked in Claude: {', '.join(mcp_st['untracked_in_claude'])}")
        if mcp_st["untracked_in_gemini"]:
            drift_details.append(f"untracked in Antigravity: {', '.join(mcp_st['untracked_in_gemini'])}")
        if mcp_st["drifted_in_claude"]:
            drift_details.append(f"drifted in Claude: {', '.join(mcp_st['drifted_in_claude'])}")
        if mcp_st["drifted_in_gemini"]:
            drift_details.append(f"drifted in Antigravity: {', '.join(mcp_st['drifted_in_gemini'])}")
        issues.append(f"MCP servers out of sync ({'; '.join(drift_details)})")
    else:
        server_count = len(mcp_st["hub"]["servers"])
        checks.append(f"MCP servers synchronized across hub and platforms ({server_count} registered)")

    # Auto-repair if requested
    repairs = []
    if fix and issues:
        link_skills_for_claude()
        link_skills_for_gemini()
        if codex_dir.is_dir():
            link_skills_for_codex()
            project_codex_rules()
        if cursor_dir.is_dir():
            from agentrc.connect import connect_cursor
            connect_cursor()
        if windsurf_dir.is_dir():
            from agentrc.connect import connect_windsurf
            connect_windsurf()
        project_gemini_rules()
        project_claude_rules()
        project_subagents()
        if not mcp_st["in_sync"]:
            _, mcp_actions = sync_mcp_servers(home, hub)
            repairs.extend(mcp_actions)
        repairs.append("Ran link_skills and projections across all platforms.")

    return {
        "status": "PASS" if not issues else "WARN",
        "passed_checks": checks,
        "issues": issues,
        "repairs": repairs,
    }
